"""Regenerate docs/data_dictionary.md from the published warehouse and the column catalog.

python scripts/generate_data_dictionary.py
"""

from __future__ import annotations

from pathlib import Path

import duckdb

from copenhagen_data_lab.config.settings import get_settings
from copenhagen_data_lab.database.catalog import TABLES, definition

OUT = Path(__file__).resolve().parents[1] / "docs" / "data_dictionary.md"
OTHER_TABLES = [
    "dim_area", "dim_sex", "dim_age", "dim_marital_status", "dim_period",
    "quality_results", "pipeline_runs", "warehouse_info",
]  # fmt: skip


def columns(con: duckdb.DuckDBPyConnection, table: str) -> list[tuple[str, str]]:
    return con.execute(
        "SELECT column_name, data_type FROM duckdb_columns() "
        "WHERE table_name = ? ORDER BY column_index",
        [table],
    ).fetchall()


def main() -> None:
    con = duckdb.connect(str(get_settings().warehouse_path), read_only=True)
    lines = [
        "# Data dictionary",
        "",
        "Generated by `scripts/generate_data_dictionary.py` from the warehouse schema and",
        "`src/copenhagen_data_lab/database/catalog.py` (the same definitions appear in the",
        "dashboard's Data Explorer). Types are DuckDB types.",
        "",
        "Columns described as *Derived* are calculated by Copenhagen Data Lab; all other values",
        "are official Statistics Denmark figures or codes from table FOLK1A.",
        "",
    ]
    try:
        for name, doc in TABLES.items():
            rows = con.execute(f"SELECT COUNT(*) FROM {name}").fetchone()[0]
            lines += [
                f"## `{name}`",
                "",
                f"*Layer:* {doc.layer} · *Grain:* {doc.grain} · "
                f"*Rows in current snapshot:* {rows:,}",
                "",
                doc.description,
                "",
                "| Column | Type | Definition |",
                "|---|---|---|",
                *(f"| `{c}` | {t} | {definition(name, c)} |" for c, t in columns(con, name)),
                "",
            ]
        lines += ["## Dimension and operations tables", ""]
        for name in OTHER_TABLES:
            cols = ", ".join(f"`{c}` ({t})" for c, t in columns(con, name))
            lines.append(f"* **`{name}`** — {cols}")
        lines += [
            "",
            "Keys and constraints: `src/copenhagen_data_lab/sql/staging/01_create_staging.sql` "
            "and `OPS_DDL` in `src/copenhagen_data_lab/pipeline/load.py`.",
            "",
        ]
    finally:
        con.close()
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
